// Proves the ffmpeg preset offline: a synthetic clip (no member voice or video), fixture
// captions and a fixture consent record. Writes social/previews/clip-overlay-story*.png.
// Run: npm run social:clip (needs ffmpeg with libass, and npm run social:fonts).
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { Resvg } from "@resvg/resvg-js";
import satori from "satori";
import { sha256 } from "./check.mjs";
import { CLIP_SCHEMA, captionOverlayArgs, checkClip, clipOverlay, toAss } from "./ffmpeg.mjs";
import { loadAssets, loadManifest } from "./render.mjs";
import { SIZE } from "./templates.mjs";

const dir = await mkdtemp(path.join(tmpdir(), "two-clip-"));
const input = path.join(dir, "synthetic.mp4");
// Synthetic 16:9 source: the overlay ground with the raised ground band, plus silence.
execFileSync("ffmpeg", [
  "-v",
  "error",
  "-y",
  "-f",
  "lavfi",
  "-i",
  "color=c=0x2e2420:s=1280x720:d=4,drawbox=y=240:w=1280:h=240:color=0x241c19:t=fill",
  "-f",
  "lavfi",
  "-i",
  "anullsrc=r=48000:cl=stereo",
  "-t",
  "4",
  "-c:v",
  "libx264",
  "-pix_fmt",
  "yuv420p",
  "-c:a",
  "aac",
  input,
]);
const manifest = await loadManifest();
const assets = await loadAssets(manifest);
const clipBytes = await readFile(input);
const fixtureAsset = {
  id: "fixture-clip-synthetic",
  kind: "clip",
  title: "Synthetic clip generated by ffmpeg lavfi (no people)",
  path: input,
  sha256: sha256(clipBytes),
  uses: ["fixture"],
  aiGenerated: false,
  depictsPeople: false,
  releaseIds: ["fixture-release-0001"],
  consent: {
    recordId: "fixture-consent-0001",
    purposes: ["organic-social"],
    channels: ["youtube-shorts"],
    expiresAt: "2027-11-04T00:00:00Z",
    withdrawnAt: null,
  },
  withdrawnAt: null,
};
const clip = {
  schema: CLIP_SCHEMA,
  revision: "fx-clip-r1",
  fixture: true,
  clip: { assetId: fixtureAsset.id, sha256: fixtureAsset.sha256 },
  title: { text: "Raid Night" },
  day: "2026-10-30",
  zone: "Europe/London",
  captions: [
    { start: 0.2, end: 2.0, text: "Left side is clear, push up with me.", source: "human" },
    { start: 2.1, end: 3.9, text: "Nice. Same again on the next wave.", source: "human" },
  ],
  disclosure: { aiAssistedCopy: false, aiGeneratedImagery: false, platformAiLabel: false },
};
const result = checkClip(clip, {
  manifest: { ...manifest, assets: [...manifest.assets, fixtureAsset] },
  now: new Date("2026-11-04T12:00:00Z"),
  platform: "youtube-shorts",
  resolveAsset: () => clipBytes,
});
if (!result.ok) throw new Error(`clip rejected: ${JSON.stringify(result.rejections)}`);

const fonts = manifest.assets
  .filter((a) => a.kind === "font")
  .map((a) => ({
    name: a.font.name,
    weight: a.font.weight,
    style: a.font.style,
    data: assets.get(a.id),
  }));
const icon = `data:image/svg+xml;base64,${assets.get("two-icon").toString("base64")}`;
const { width, height } = SIZE.story;
const svg = await satori(clipOverlay(clip, { icon }), { width, height, fonts });
const overlay = path.join(dir, "overlay.png");
await writeFile(overlay, new Resvg(svg).render().asPng());
const ass = path.join(dir, "captions.ass");
await writeFile(ass, toAss(clip.captions));
const output = path.join(dir, "out.mp4");
const fontsDir = path.resolve("social/fonts");
execFileSync("ffmpeg", [
  "-v",
  "error",
  ...captionOverlayArgs({ input, overlay, ass, fontsDir, output }),
]);
for (const [suffix, vf] of [
  ["", "null"],
  ["-phone", "scale=390:-1"],
]) {
  execFileSync("ffmpeg", [
    "-v",
    "error",
    "-y",
    "-ss",
    "1",
    "-i",
    output,
    "-frames:v",
    "1",
    "-vf",
    vf,
    `social/previews/clip-overlay-story${suffix}.png`,
  ]);
}
console.log(`clip ok; frame written to social/previews/clip-overlay-story.png (work dir ${dir})`);
